import {
  ChangeDetectionStrategy,
  Component,
  computed,
  effect,
  input,
  linkedSignal,
  output,
  Signal,
  untracked,
  WritableSignal,
} from '@angular/core';
import {
  disabled,
  FieldTree,
  FormField,
  FormRoot,
  form,
  maxLength,
  required,
} from '@angular/forms/signals';

import { MatFormField, MatLabel, MatError } from '@angular/material/form-field';
import { MatInput } from '@angular/material/input';
import { MatSelect } from '@angular/material/select';
import { MatOption } from '@angular/material/core';
import { MatButton, MatIconButton } from '@angular/material/button';
import { MatIcon } from '@angular/material/icon';
import { MatTooltip } from '@angular/material/tooltip';

import { Flag, FlagSetComponent } from '@myrmidon/cadmus-ui-flag-set';
import {
  FacetDefinition,
  FlagDefinition,
  Item,
} from '@myrmidon/cadmus-core';

/**
 * The editable shape behind the item metadata form. Text fields use '' as
 * their empty value, as they are bound to native inputs.
 */
export interface ItemMetadataControls {
  title: string;
  sortKey: string;
  description: string;
  facet: string | null;
  group: string;
  flags: number;
}

/**
 * The item metadata edited by the metadata editor.
 */
export type ItemMetadata = Pick<
  Item,
  'title' | 'sortKey' | 'description' | 'facetId' | 'groupId' | 'flags'
>;

/**
 * The type of metadata which can be generated by the server for an item:
 * T=title, D=description.
 */
export type ItemMetadataGenerationKey = 'T' | 'D';

/**
 * Item -> draft.
 */
export function toItemMetadataDraft(
  item: Item | undefined,
): ItemMetadataControls {
  return {
    title: item?.title || '',
    sortKey: item?.sortKey || '',
    description: item?.description || '',
    facet: item?.facetId ?? null,
    group: item?.groupId ?? '',
    flags: item?.flags ?? 0,
  };
}

/**
 * Draft -> metadata. Normalizes values (trimming), so the metadata saved
 * from a draft may differ from the draft itself.
 */
export function toItemMetadata(v: ItemMetadataControls): ItemMetadata {
  return {
    title: v.title.trim(),
    sortKey: v.sortKey.trim(),
    description: v.description.trim(),
    facetId: v.facet?.trim() || '',
    groupId: v.group.trim(),
    flags: v.flags,
  };
}

/**
 * Item -> metadata, or undefined if no item.
 */
export function itemMetadataOf(item: Item | undefined): ItemMetadata | undefined {
  return item
    ? {
        title: item.title,
        sortKey: item.sortKey,
        description: item.description,
        facetId: item.facetId,
        groupId: item.groupId,
        flags: item.flags,
      }
    : undefined;
}

/**
 * Item metadata editor. This is a "dumb" editor for the metadata of an
 * item (title, sort key, description, facet, group and flags). It edits
 * the item received in its `item` input, and emits `saveRequest` with the
 * edited metadata; it never saves by itself. The host (e.g. the item editor
 * page, which loads the item from its route) is responsible for saving and
 * for any other operation, which this editor just requests.
 *
 * When `readonly` is true, the editor just displays the item's metadata:
 * its form is disabled, flags are shown as a static list, and all the
 * action buttons are hidden, so that nothing can be requested.
 */
@Component({
  selector: 'cadmus-item-metadata-editor',
  templateUrl: './item-metadata-editor.component.html',
  styleUrls: ['./item-metadata-editor.component.css'],
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [
    FormField,
    FormRoot,
    MatFormField,
    MatLabel,
    MatInput,
    MatError,
    MatSelect,
    MatOption,
    MatButton,
    MatIconButton,
    MatIcon,
    MatTooltip,
    FlagSetComponent,
  ],
})
export class ItemMetadataEditorComponent {
  /**
   * The item whose metadata is edited. Its parts, if any, are ignored.
   */
  public readonly item = input<Item | undefined>();

  /**
   * The facet definitions to pick the item's facet from.
   */
  public readonly facets = input<FacetDefinition[]>([]);

  /**
   * The flags definitions.
   */
  public readonly flagDefinitions = input<FlagDefinition[]>([]);

  /**
   * The current user level (0-4). Admin flags (level 4) can be changed
   * only by admins; actions require at least an operator (level 2).
   */
  public readonly userLevel = input<number>(0);

  /**
   * True when the host is busy, disabling the action buttons.
   */
  public readonly busy = input<boolean>(false);

  /**
   * True to show the buttons for generating title and description.
   */
  public readonly hasMetadataBuilders = input<boolean>(false);

  /**
   * True to make the editor read-only.
   */
  public readonly readonly = input<boolean>(false);

  /**
   * Emitted with the normalized metadata when the user saves.
   */
  public readonly saveRequest = output<ItemMetadata>();

  /**
   * Emitted when the user requests to generate items using this item
   * as a template.
   */
  public readonly generateItemsRequest = output();

  /**
   * Emitted when the user requests to generate the title (T) or the
   * description (D). The host should then call `setGenerated`.
   */
  public readonly generateRequest = output<ItemMetadataGenerationKey>();

  /**
   * Emitted when the dirty state of the form changes.
   */
  public readonly dirtyChange = output<boolean>();

  /** Flags adapted for FlagSetComponent; admin flags excluded for non-admins. */
  public readonly flagSetFlags: Signal<Flag[]>;
  /** Admin-only flags shown read-only to non-admin users. */
  public readonly adminFlagDefs: Signal<FlagDefinition[]>;
  /** Currently checked flag IDs derived from the flags form control value. */
  public readonly checkedFlagIds: Signal<string[]>;
  /** Flag definitions of the checked flags, displayed when read-only. */
  public readonly checkedFlagDefs: Signal<FlagDefinition[]>;

  // item metadata form: derived from the edited item
  private readonly _metadata: WritableSignal<ItemMetadataControls>;
  public readonly metadata: FieldTree<ItemMetadataControls>;
  private _lastDirty = false;

  constructor() {
    // The live draft is kept when the same item is reloaded with unchanged
    // metadata, and on the echo of our own save; otherwise (another item,
    // or a saved item coming back different, e.g. with a new sort key
    // computed by the server) it is rebuilt.
    this._metadata = linkedSignal<Item | undefined, ItemMetadataControls>({
      source: this.item,
      computation: (item, previous) =>
        previous &&
        // the same item reloaded with unchanged metadata (e.g. after a
        // part operation): keep any unsaved edits
        ((item?.id === previous.source?.id &&
          JSON.stringify(itemMetadataOf(item)) ===
            JSON.stringify(itemMetadataOf(previous.source))) ||
          // the echo of our own save
          JSON.stringify(itemMetadataOf(item)) ===
            JSON.stringify(toItemMetadata(previous.value)))
          ? previous.value
          : toItemMetadataDraft(item),
    });
    this.metadata = form(
      this._metadata,
      (path) => {
        // read-only: the root path's state is inherited by all the fields
        disabled(path, () => this.readonly());
        required(path.title);
        maxLength(path.title, 500);
        // the sort key is computed by the server
        disabled(path.sortKey);
        required(path.sortKey);
        maxLength(path.sortKey, 500);
        required(path.description);
        maxLength(path.description, 1000);
        required(path.facet);
        maxLength(path.group, 100);
      },
      {
        // the save button and Enter in its text inputs submit the item
        submission: {
          action: async () => {
            this.save();
            return undefined;
          },
        },
      },
    );

    // once the draft mirrors the edited item again, clear interaction state
    effect(() => {
      const draft = this._metadata();
      untracked(() => {
        if (
          JSON.stringify(draft) ===
          JSON.stringify(toItemMetadataDraft(this.item()))
        ) {
          this.metadata().reset();
        }
      });
    });

    // propagate dirty state changes
    effect(() => {
      const dirty = this.metadata().dirty();
      untracked(() => {
        if (dirty !== this._lastDirty) {
          this._lastDirty = dirty;
          this.dirtyChange.emit(dirty);
        }
      });
    });

    // flags for FlagSetComponent: exclude admin flags for non-admins
    this.flagSetFlags = computed<Flag[]>(() =>
      this.flagDefinitions()
        .filter((def) => this.userLevel() >= 4 || !def.isAdmin)
        .map((def) => ({
          id: String(def.id),
          label: def.label,
          color: '#' + def.colorKey,
        })),
    );

    // admin-only flags shown read-only when user is not admin
    this.adminFlagDefs = computed<FlagDefinition[]>(() => {
      if (this.userLevel() >= 4) return [];
      return this.flagDefinitions().filter((def) => def.isAdmin === true);
    });

    // checked flag IDs derived from the bitmask value
    this.checkedFlagIds = computed<string[]>(() => {
      const value = this.metadata.flags().value();
      return this.flagDefinitions()
        .filter((def) => (value & def.id) !== 0)
        .map((def) => String(def.id));
    });

    this.checkedFlagDefs = computed<FlagDefinition[]>(() => {
      const value = this.metadata.flags().value();
      return this.flagDefinitions().filter((def) => (value & def.id) !== 0);
    });
  }

  /**
   * True when the form has unsaved changes.
   */
  public isDirty(): boolean {
    return this.metadata().dirty();
  }

  /**
   * Called when the FlagSetComponent emits new checked flag IDs.
   * Converts the string IDs back to a bitmask integer and updates
   * the flags form control, preserving admin-flag bits for non-admins.
   */
  public onFlagCheckedIdsChange(ids: string[]): void {
    if (this.readonly()) {
      return;
    }
    let value = 0;
    // non-admins cannot change admin flags: preserve their current bits
    if (this.userLevel() < 4) {
      const current = this.metadata.flags().value();
      for (const def of this.flagDefinitions()) {
        if (def.isAdmin && (current & def.id) !== 0) {
          value |= def.id;
        }
      }
    }
    for (const id of ids) {
      value |= Number(id);
    }
    this.metadata.flags().value.set(value);
    this.metadata.flags().markAsDirty();
  }

  /**
   * Set the generated title (T) or description (D), as received by the
   * host after a `generateRequest`.
   *
   * @param key The metadata key.
   * @param value The generated value.
   */
  public setGenerated(key: ItemMetadataGenerationKey, value: string): void {
    if (this.readonly()) {
      return;
    }
    const field =
      key === 'T' ? this.metadata.title : this.metadata.description;
    field().value.set(value);
    field().markAsDirty();
  }

  /**
   * Clear the form's interaction state, e.g. once the host has saved the
   * metadata, so that it is no more dirty.
   */
  public markSaved(): void {
    this.metadata().reset();
  }

  /**
   * Request to save the metadata, if valid and not read-only.
   */
  public save(): void {
    if (this.readonly() || this.busy() || !this.metadata().valid()) {
      return;
    }
    this.saveRequest.emit(toItemMetadata(this._metadata()));
  }

  public requestGenerate(key: ItemMetadataGenerationKey): void {
    if (this.readonly() || this.busy()) {
      return;
    }
    this.generateRequest.emit(key);
  }

  public requestGenerateItems(): void {
    if (this.readonly() || this.busy()) {
      return;
    }
    this.generateItemsRequest.emit();
  }
}
